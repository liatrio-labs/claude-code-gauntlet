def capture(
    tmp_path,
    monkeypatch,
    capsys,
    forge_factory,
    platform,
    findings,
    raw_diff,
    owner="withastro",
    repo="astro",
    number=1234,
):
    run = invoke_posting(
        tmp_path,
        monkeypatch,
        capsys,
        forge_factory,
        {
            "owner": owner,
            "repo": repo,
            "pr_number": number,
            "platform": platform,
            "sha": _GH_SHA,
            "review_body": "Automated review summary.",
            "findings": findings,
        },
        diff=raw_diff,
        refs=JsonFetch(
            [
                {
                    "base_commit_sha": _GL_BASE,
                    "head_commit_sha": _GL_HEAD,
                    "start_commit_sha": _GL_START,
                }
            ],
            None,
        ),
    )
    assert run.code == 0
    assert run.requests == ()
    assert run.head_calls == ()
    assert forge_factory.calls == [platform]
    assert [call.method for call in run.fake.calls] == (
        ["diff", "ensure_available"]
        if platform == "github"
        else ["diff", "ensure_available", "ensure_available", "diff_refs"]
    )
    return run


