def _facts_tracked(**kwargs):
    calls: list[list[str]] = []
    inner = _fake_git_run(**kwargs)

    def _run(cmd, *a, **k):
        calls.append(cmd)
        return inner(cmd, *a, **k)

    return (_run, calls)


