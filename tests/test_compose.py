@pytest.mark.parametrize(
    "finding,expected_body,expected_key", KEY_PINS_CASES.values(), ids=KEY_PINS_CASES
)
def test_key_pins(finding, expected_body, expected_key, monkeypatch):
    monkeypatch.setattr(compose, "BRAND_TRAILER", "Changed identity")

    def branded(*args, **kwargs):
        raise AssertionError("key material must exclude the branded renderer")

    monkeypatch.setattr(compose, "render_comment_body", branded)
    originals = (
        (finding,)
        if isinstance(finding, UserDict)
        else (
            {**finding},
            {
                **finding,
                "suggested_fix_code": "replacement",
                "rule_source": "repo_precedent",
            },
        )
    )
    for original in originals:
        before = copy.deepcopy(original)
        assert compose.key_material_body(original) == expected_body
        key = compose.finding_key(
            original["file"],
            original["line"],
            original.get("title", ""),
            expected_body,
        )
        assert key == expected_key
        assert original == before


