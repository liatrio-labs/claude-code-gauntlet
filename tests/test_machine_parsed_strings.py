"""Machine-parsed string registry presence guard (Issue #37).

docs/machine-parsed-strings.md is the living list of strings another component
parses. Each row names producer path(s) and parser path(s). Drift here is silent
and functional — three recent investigations each re-derived this list before
changing output. Presence/byte checks only; no semantic shape equality.

EVERY listed path must contain the bytes, producers and parsers alike. Requiring
only one parser to match let four rows name files that never held the string
(`detect_prior_review.py`, `tests/test_validate_ndjson.py`, `bench/runner/invoke.py`),
because the producer was also listed and satisfied the check on its own. A row
with no byte-level reader writes `—` and explains itself in the notes.
"""

import re
import unittest
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
REGISTRY = REPO / "docs" / "machine-parsed-strings.md"

_ROW = re.compile(r"^\|\s*`([^`]+)`\s*\|\s*([^|]+)\|\s*([^|]+)\|\s*([^|]*)\|\s*$")


NO_PARSER = "—"  # em dash: "nothing reads these bytes", explained in notes


def _strip_ticks(token: str) -> str:
    token = token.strip()
    if token.startswith("`") and token.endswith("`"):
        return token[1:-1]
    return token


def parse_registry(text: str) -> list[dict]:
    rows = []
    for line in text.splitlines():
        m = _ROW.match(line)
        if not m:
            continue
        string, producers, parsers, notes = (c.strip() for c in m.groups())
        if string == "string" or set(string) <= {"-", " "}:
            continue
        rows.append(
            {
                "string": string,
                "producers": [
                    _strip_ticks(p) for p in producers.split(",") if p.strip()
                ],
                "parsers": [_strip_ticks(p) for p in parsers.split(",") if p.strip()],
                "notes": notes,
            }
        )
    return rows


class TestMachineParsedStrings(unittest.TestCase):
    def test_parse_registry_handles_fixture_shapes(self):
        # Fixture-based unit test: the live-registry presence checks only exercise
        # today's table shape. A broken _ROW / split / NO_PARSER path must fail
        # here even when the real registry happens to still parse.
        fixture = "\n".join(
            [
                "| string | producer path(s) | parser path(s) | notes |",
                "| --- | --- | --- | --- |",
                "| `TokA` | `a.py`, `b.py` | `c.py` | multi producers |",
                "| `TokB` | `only.py` | `—` | honest empty |",
                "| `TokC` | `p.py` | `—` | |",  # NO_PARSER without a note — still parses
                "| string | producer path(s) | parser path(s) | notes |",  # header repeat ignored
                "| --- | --- | --- | --- |",
            ]
        )
        rows = parse_registry(fixture)
        by_string = {r["string"]: r for r in rows}
        self.assertEqual(set(by_string), {"TokA", "TokB", "TokC"})
        self.assertEqual(by_string["TokA"]["producers"], ["a.py", "b.py"])
        self.assertEqual(by_string["TokA"]["parsers"], ["c.py"])
        self.assertEqual(by_string["TokA"]["notes"], "multi producers")
        self.assertEqual(by_string["TokB"]["parsers"], [NO_PARSER])
        self.assertEqual(by_string["TokB"]["notes"], "honest empty")
        self.assertEqual(by_string["TokC"]["parsers"], [NO_PARSER])
        self.assertEqual(by_string["TokC"]["notes"], "")

    def test_registry_exists_and_has_seed_rows(self):
        self.assertTrue(REGISTRY.is_file(), "docs/machine-parsed-strings.md missing")
        rows = parse_registry(REGISTRY.read_text(encoding="utf-8"))
        strings = {r["string"] for r in rows}
        required = {
            "Headless config:",
            "code-gauntlet-findings",
            "Generated by code-gauntlet",
            "Reviewed up to:",
            "HEADLESS CONFIG ERROR:",
            "HEADLESS INPUT ERROR:",
            "code-gauntlet v3 requires Claude Code >= 2.1.154 with dynamic workflows. Install the pre-rename deep-review v2.x for older CLIs.",
            "[validate_ndjson]",
            "the deltas carry a checksum",
            "PAYLOAD_JSON:",
            'PRODUCT = "code-gauntlet"',
        }
        missing = required - strings
        self.assertEqual(missing, set(), f"registry missing seed strings: {missing}")

    def test_every_listed_path_contains_the_string(self):
        rows = parse_registry(REGISTRY.read_text(encoding="utf-8"))
        self.assertGreaterEqual(len(rows), 9)
        offenders = {}
        for row in rows:
            s = row["string"]
            listed = [("producer", p) for p in row["producers"]]
            listed += [("parser", p) for p in row["parsers"] if p != NO_PARSER]
            for role, rel in listed:
                path = REPO / rel
                if not path.is_file():
                    offenders[f"{s} {role} {rel}"] = "missing file"
                elif s not in path.read_text(encoding="utf-8"):
                    offenders[f"{s} {role} {rel}"] = "string absent"
        self.assertEqual(offenders, {}, f"registry presence failures: {offenders}")

    def test_every_row_names_a_producer_and_resolves_its_parser_column(self):
        rows = parse_registry(REGISTRY.read_text(encoding="utf-8"))
        offenders = {}
        for row in rows:
            s = row["string"]
            if not row["producers"]:
                offenders[s] = "no producer listed"
            if not row["parsers"]:
                offenders[f"{s} parsers"] = f"empty — write {NO_PARSER} and explain"
            elif NO_PARSER in row["parsers"]:
                if row["parsers"] != [NO_PARSER]:
                    offenders[f"{s} parsers"] = f"{NO_PARSER} mixed with real paths"
                elif not row["notes"]:
                    offenders[f"{s} parsers"] = (
                        f"{NO_PARSER} without a note explaining it"
                    )
        self.assertEqual(offenders, {}, f"registry shape failures: {offenders}")


if __name__ == "__main__":
    unittest.main()
