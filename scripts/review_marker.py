#!/usr/bin/env python3
"""
review_marker.py — the prior-review signal for code-gauntlet: one module, both directions.

This module is the single source of truth for the signal a posted review leaves
behind on a PR/MR and that a later rerun reads back:

* ``post_review.py`` imports the builders (``build_footer``) — it is the ONLY
  code that writes the signal. Models never hand-compose it; documentation that
  once templated it now points here:
  ``<!-- Canonical source: scripts/review_marker.py -->``.
* ``detect_prior_review.py`` imports the parsers (``select_latest``,
  ``detect_signal``) — it is the ONLY code that reads it.

The signal has two halves, both machine-written and independently idempotent —
a prose footer line and an HTML-comment marker, appended to the review summary
body separated by a horizontal rule::

    ---
    Generated by code-gauntlet | Reviewed up to: <sha>

    <!-- code-gauntlet-findings: {"version":"3.0","findings_count":N,"sha":"<sha>"} -->

Wire-format rules (the marker lives forever in users' PR histories, written by
whatever plugin version they happened to run):

* **No reader ever branches on ``version``.** It is informational/forensic only.
  Two token generations exist in the wild — ``code-gauntlet-findings`` (current)
  and ``deep-review-findings`` (pre-rename) — and *both* carry ``"version":"3.0"``,
  so the field has already lied across a plugin generation. Dispatching on it
  would be dispatching on a known-false value. This rule is pinned by a test.
* Readers are **liberal and duck-typed**: the only field detection requires is a
  SHA-shaped value under key ``sha``. Every other key is optional and unknown
  keys are preserved verbatim in the returned payload, so future producers need
  no parser change.
* Both token generations are recognized, mirroring the repo's existing legacy
  fallbacks (``merge_findings.py`` filename fallback, ``filter_findings.py``
  config-marker fallback).

The ``findings`` payload key is a reserved, writer-supported extension slot owned
by issue #36: supply ``findings=`` and it is emitted last; omit it (always, today)
and the key is absent — byte-identical to the legacy payload.

A SECOND, separate wire format lives here too: the per-finding delivery marker
``post_review.py`` appends to every inline GitLab discussion it posts on the live
wire, and ``detect_prior_review.py`` reads back so a rerun after a partial
delivery does not repost the discussions already on the MR::

    <!-- code-gauntlet-finding-key: {"sha":"<sha>","key":"<16 lowercase hex>"} -->

It shares no token bytes with the summary marker above, so neither reader can
match the other's marker and a body carrying both is unambiguous. Unlike the
summary payload it is validated rather than duck-typed: a finding's title and
body reach the wire RAW (only ``suggestion``/``claude_md_rule``/``spec_text``
are sanitized), so a marker spelled inside a finding's own text is hostile input
that must never be collected as a delivery record.

The shadowing this relies on ("the mechanical marker is APPENDED, so it always
wins last-wins parsing over anything a forged one said earlier") holds for a
posted inline discussion, where nothing but the marker follows the rendered
finding. It does NOT hold inside ``post_review.py``'s degraded-findings section
(``build_skipped_section``, issue #192): a skipped finding's rendered text sits
inside the review body / GitLab summary note, and nothing mechanical is
guaranteed to follow it there before the NEXT finding's text or the end of the
body. That section instead neutralizes every ``<!--`` in a finding's rendered
text to ``&lt;!--`` before insertion, so no finding-key (or summary-marker)
syntax can ever open a real HTML comment from inside it.

No external Python dependencies — stdlib only.
"""

import json
import math
import re
from datetime import datetime, timezone

# ---------------------------------------------------------------------------
# Wire format constants
# ---------------------------------------------------------------------------

MARKER_TOKEN = "code-gauntlet-findings"
LEGACY_MARKER_TOKEN = "deep-review-findings"  # pre-rename; still in the wild
MARKER_TOKENS = (MARKER_TOKEN, LEGACY_MARKER_TOKEN)
# Per-finding delivery marker. Neither this token nor its regex below can be
# reached by the summary-marker patterns above (nor they by it): the summary
# tokens end in `findings`, this one continues into `-key`, so the `:` each
# pattern demands right after its token cannot follow the other's bytes.
FINDING_MARKER_TOKEN = "code-gauntlet-finding-key"
PRODUCT = "code-gauntlet"
LEGACY_PRODUCT = "deep-review"
MARKER_VERSION = "3.0"  # informational; never dispatched on
SHA_RE = re.compile(r"\b([0-9a-f]{7,40})\b")  # git object ids are lowercase hex

# `<!--` … token … `:` with arbitrary whitespace (including newlines) anywhere
# between the pieces, so `<!--code-gauntlet-findings:{…}-->` and newline-broken
# forms both parse. The JSON that follows is extracted by balanced-brace scanning,
# never by a regex terminated at `-->` — a `findings` array may legitimately carry
# `-->` inside a string value.
_MARKER_RE = re.compile(
    r"<!--\s*(" + "|".join(re.escape(t) for t in MARKER_TOKENS) + r")\s*:\s*"
)

# The finding payload is two short strings this module writes itself, so a plain
# regex spans it: no `{`/`}` can appear inside, and every candidate is therefore a
# disjoint, brace-bounded span. That is why the finding reader needs no equivalent
# of _MAX_MARKER_SCANS — scanning every candidate is linear in the body, whereas
# the summary marker's balanced-brace scan is not.
_FINDING_MARKER_RE = re.compile(
    r"<!--\s*" + re.escape(FINDING_MARKER_TOKEN) + r"\s*:\s*(\{[^{}]*\})\s*-->"
)
_FINDING_KEY_RE = re.compile(r"[0-9a-f]{16}")

_PROSE_LABEL_RE = re.compile(r"Reviewed\s+up\s+to\s*:", re.IGNORECASE)

_ISO8601_RE = re.compile(r"^\d{4}-\d{2}-\d{2}")

# How many marker candidates find_marker will attempt to parse, counting back
# from the end of the body. A real body carries one. A body carrying dozens of
# unparseable ones is hostile input on a public surface, and the safe answer
# there is "no signal" (a full review) rather than an unbounded parse.
_MAX_MARKER_SCANS = 32


def is_sha_shaped(value):
    """Return True when *value* is a 7-40 character lowercase hex git object id."""
    return isinstance(value, str) and SHA_RE.fullmatch(value.strip()) is not None


# ---------------------------------------------------------------------------
# Write side — what a review leaves behind
# ---------------------------------------------------------------------------


def build_marker(sha, findings_count, findings=None):
    """Return the machine-readable HTML-comment marker.

    Key order is fixed: ``version``, ``findings_count``, ``sha``, then ``findings``
    last and only when *findings* is not None (issue #36's extension slot).
    """
    payload = {
        "version": MARKER_VERSION,
        "findings_count": findings_count,
        "sha": sha,
    }
    if findings is not None:
        payload["findings"] = findings
    return f"<!-- {MARKER_TOKEN}: {json.dumps(payload, separators=(',', ':'))} -->"


def build_finding_marker(sha, key):
    """Return the per-finding delivery marker for one inline comment body.

    Key order is fixed: ``sha``, then ``key``. The caller composes layout — no
    surrounding newlines. *key* is expected to be 16 lowercase hex characters;
    anything else round-trips as bytes but is rejected by
    :func:`find_finding_marker`, so a bad key degrades to "not deduped" rather
    than to a silently wrong match.
    """
    payload = {"sha": sha, "key": key}
    return (
        f"<!-- {FINDING_MARKER_TOKEN}: {json.dumps(payload, separators=(',', ':'))} -->"
    )


def build_prose_footer(sha):
    """Return the human-readable footer line. No surrounding newlines — the
    caller composes layout."""
    return f"Generated by {PRODUCT} | Reviewed up to: {sha}"


def build_footer(findings_count, sha, body="", findings=None):
    """Return the string to append to *body* — prose footer plus marker.

    Both halves are guarded independently against duplication: if *body* already
    carries a recognizable marker the marker half is omitted, and if it already
    carries a ``Generated by <product> | Reviewed up to:`` line the prose half is
    omitted. When both are present the empty string is returned, so appending
    twice is a no-op.

    *body* and *findings* are keyword-with-default so the two-positional-argument
    call sites keep working unchanged.
    """
    text = body if isinstance(body, str) else ""
    # Suppress a half only when what is already there is something the READER
    # would accept AND records THIS sha. Guarding on find_marker (any parseable
    # payload) let a body with a sha-less marker plus a bare "Generated by ..."
    # line suppress both halves and post a review carrying no detectable signal;
    # guarding without the sha check let a stale/foreign marker survive and win
    # the reader's last-wins rule while our prose line advertised a different
    # commit. Both halves carry the sha check for the same reason: a footer left
    # by a model copying the reference rendering must not suppress the real one.
    existing = detect_signal(text)
    want_marker = not (
        existing and existing.get("signal") == "marker" and existing.get("sha") == sha
    )
    want_prose = not (has_prose_footer(text) and parse_prose_footer(text) == sha)

    if not want_marker and not want_prose:
        return ""

    marker = build_marker(sha, findings_count, findings) if want_marker else ""
    if not want_prose:
        return "\n\n" + marker

    footer = "\n\n---\n" + build_prose_footer(sha)
    if want_marker:
        footer += "\n\n" + marker
    return footer


# ---------------------------------------------------------------------------
# Read side — parsing what a previous review left behind
# ---------------------------------------------------------------------------


def _has_non_finite(value, depth=0):
    """True when *value* contains a float that json.dumps cannot emit as valid JSON.

    ``parse_constant`` only sees the literal ``NaN``/``Infinity`` tokens. An
    ordinary numeric token that overflows — ``1e999`` — becomes ``inf`` without
    ever consulting it, and ``json.dumps`` then writes a bare ``Infinity``,
    making our own stdout invalid JSON for whoever parses it.
    """
    if depth > 64:
        return True
    if isinstance(value, float):
        return math.isnan(value) or value in (float("inf"), float("-inf"))
    if isinstance(value, dict):
        return any(_has_non_finite(v, depth + 1) for v in value.values())
    if isinstance(value, (list, tuple)):
        return any(_has_non_finite(v, depth + 1) for v in value)
    return False


def _reject_constant(name):
    """Reject JSON's non-standard NaN/Infinity literals.

    ``json.loads`` accepts them by default and they survive into the emitted
    marker, where ``json.dumps`` re-emits bare ``NaN``/``Infinity`` tokens — so a
    hostile marker could make the detector's own stdout invalid JSON for the
    caller parsing it. Raising here makes such a payload simply malformed.
    """
    raise ValueError(f"non-standard JSON constant: {name}")


def _scan_json_at(text, start):
    """Return ``(parsed_object_or_None, index_after_object)``.

    Balanced-brace scan from *start* (which must index a ``{``) that respects
    string literals and backslash escapes, so a ``}`` — or a ``-->`` — inside a
    JSON string value cannot terminate the object early. Same idiom as
    ``merge_findings.py::_try_parse_json_at``; deliberately duplicated rather
    than imported across scripts.
    """
    depth = 0
    in_string = False
    escape_next = False
    i = start
    while i < len(text):
        ch = text[i]
        if escape_next:
            escape_next = False
        elif ch == "\\" and in_string:
            escape_next = True
        elif ch == '"':
            in_string = not in_string
        elif not in_string:
            if ch == "{":
                depth += 1
            elif ch == "}":
                depth -= 1
                if depth == 0:
                    try:
                        parsed = json.loads(
                            text[start : i + 1], parse_constant=_reject_constant
                        )
                    except (ValueError, RecursionError):
                        return None, i + 1
                    if _has_non_finite(parsed):
                        return None, i + 1
                    return parsed, i + 1
        i += 1
    return None, len(text)


def find_marker(text):
    """Return the payload of the LAST syntactically valid marker in *text*, else None.

    Last-wins because ``post_review.py`` *appends*: its mechanical marker always
    follows any marker a model may have composed earlier in the same body. A
    malformed occurrence never shadows a valid one elsewhere in the text.

    The returned dict is the parsed payload — unknown keys preserved verbatim —
    plus two injected keys: ``_token`` (which token matched) and ``_legacy``
    (True when the pre-rename token produced it). Never raises.
    """
    if not isinstance(text, str) or not text:
        return None
    try:
        # Scan candidates from the END backwards and stop at the first that
        # parses. The answer is defined as the last valid marker, so in the
        # normal case (a body whose final marker is the mechanical one) this
        # costs exactly one scan. Forward-scanning every occurrence made a body
        # full of unclosed `<!--code-gauntlet-findings:{` tokens cost
        # O(tokens x length) — minutes of Phase 1 stall from one hostile comment.
        matches = list(_MARKER_RE.finditer(text))
        for match in reversed(matches[-_MAX_MARKER_SCANS:]):
            start = match.end()
            if start >= len(text) or text[start] != "{":
                continue
            payload, _ = _scan_json_at(text, start)
            if isinstance(payload, dict):
                found = dict(payload)
                found["_token"] = match.group(1)
                found["_legacy"] = match.group(1) == LEGACY_MARKER_TOKEN
                return found
        return None
    except Exception:  # noqa: BLE001  # pragma: no cover - a reader never raises
        return None


def find_finding_marker(text):
    """Return ``{"sha", "key"}`` from the LAST valid finding marker in *text*, else None.

    Last-wins for the reason :func:`find_marker` is: ``post_review.py`` APPENDS its
    marker, so the mechanical one always follows anything a finding's own unsanitized
    prose spelled earlier in the same body — such a forgery can be shadowed, never
    shadow.

    Both fields are validated before a payload is accepted: ``key`` must be 16
    lowercase hex characters and ``sha`` SHA-shaped. A payload of the right syntax but
    the wrong types (``"key": []``) is skipped rather than returned — the caller
    collects keys into a set, and an unhashable one would abort a delivery mid-loop.
    Only those two fields come back: nothing downstream echoes this payload, so it
    carries no forward-compatibility slot to preserve. Never raises.
    """
    if not isinstance(text, str) or not text:
        return None
    try:
        for candidate in reversed(_FINDING_MARKER_RE.findall(text)):
            try:
                payload = json.loads(candidate)
            except (ValueError, RecursionError):
                continue
            # No isinstance(dict) guard: the regex above spans a brace-delimited
            # literal, so a successful parse cannot be anything else.
            key = payload.get("key")
            if not isinstance(key, str) or not _FINDING_KEY_RE.fullmatch(key):
                continue
            if not is_sha_shaped(payload.get("sha")):
                continue
            return {"sha": payload["sha"].strip(), "key": key}
        return None
    except Exception:  # noqa: BLE001  # pragma: no cover - a reader never raises
        return None


def has_prose_footer(text):
    """True when *text* carries a ``Generated by <product>`` line (either generation)."""
    if not isinstance(text, str):
        return False
    return f"Generated by {PRODUCT}" in text or f"Generated by {LEGACY_PRODUCT}" in text


def parse_prose_footer(text):
    """Return the last SHA-shaped token following a ``Reviewed up to:`` label, else None.

    Tolerates backticks, markdown emphasis, and a trailing ``|`` around the SHA.
    Never raises.
    """
    if not isinstance(text, str) or not text:
        return None
    try:
        found = None
        for match in _PROSE_LABEL_RE.finditer(text):
            tail = text[match.end() :]
            newline = tail.find("\n")
            if newline != -1:
                tail = tail[:newline]
            sha_match = SHA_RE.search(tail)
            if sha_match:
                found = sha_match.group(1)
        return found
    except Exception:  # noqa: BLE001  # pragma: no cover - a reader never raises
        return None


def _prose_is_legacy(text):
    """True when only the pre-rename product name appears in *text*."""
    if not isinstance(text, str):
        return False
    if f"Generated by {PRODUCT}" in text:
        return False
    return f"Generated by {LEGACY_PRODUCT}" in text


def detect_signal(text):
    """Return the prior-review signal carried by *text*, or None.

    Shape::

        {
          "sha":    "<7-40 hex>",       # from marker payload["sha"], else prose footer
          "signal": "marker" | "footer",
          "legacy": bool,               # legacy token or legacy product name won
          "marker": {...} | None,       # full parsed payload, None for footer-only
        }

    A valid marker whose ``sha`` is SHA-shaped wins over the prose footer. If a
    marker exists but its ``sha`` is missing or malformed, the prose footer is
    tried; if that also fails the answer is None — a signal with no usable SHA is
    not actionable. Never raises, and never branches on ``version``.

    The footer branch requires the product attribution (``Generated by
    code-gauntlet`` / ``Generated by deep-review``) as well as the SHA: a bare
    ``Reviewed up to: <sha>`` identifies no tool, and a human writing that phrase
    in a PR comment must not be mistaken for a prior code-gauntlet review.
    """
    if not isinstance(text, str) or not text:
        return None
    marker = find_marker(text)
    if marker is not None and is_sha_shaped(marker.get("sha")):
        return {
            "sha": marker["sha"].strip(),
            "signal": "marker",
            "legacy": bool(marker.get("_legacy")),
            "marker": marker,
        }
    sha = parse_prose_footer(text) if has_prose_footer(text) else None
    if sha:
        return {
            "sha": sha,
            "signal": "footer",
            "legacy": _prose_is_legacy(text),
            "marker": None,
        }
    return None


def _sort_key(timestamp):
    """Return a comparable UTC key for an ISO8601 *timestamp*, or "" if unusable.

    Comparing the raw strings is wrong the moment a producer emits a UTC offset
    instead of ``Z``: ``2026-07-26T01:00:00+02:00`` (23:00Z on the 25th) sorts
    ABOVE ``2026-07-26T00:30:00Z``, picking the older signal as the newest.
    Parsing to an absolute instant removes the ordering from the spelling.

    Every usable value returns the SAME key shape — a zero-padded epoch string —
    so keys stay mutually comparable; a naive timestamp is read as UTC. Anything
    unparseable returns "" and sorts lowest, as before.
    """
    if not isinstance(timestamp, str) or not _ISO8601_RE.match(timestamp):
        return ""
    try:
        # fromisoformat only learned to accept a trailing "Z" in 3.11 and the
        # supported floor here is 3.10, so normalize the zone spelling first.
        parsed = datetime.fromisoformat(timestamp.strip().replace("Z", "+00:00"))
    except ValueError:
        return ""
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=timezone.utc)
    # Offset by an epoch-safe constant so pre-1970 instants stay non-negative and
    # therefore still sort correctly as fixed-width strings.
    return f"{parsed.timestamp() + 1e12:020.6f}"


def select_latest(entries):
    """Return the newest signal among *entries*, or None when none carry one.

    *entries* is an iterable of ``{"body", "timestamp", "source", "id"}``. Bodies
    are run through :func:`detect_signal`; among those that produce a signal the
    winner is the one with the latest absolute instant, as computed by
    :func:`_sort_key` — NOT a lexicographic compare of the raw strings, which
    picks the older signal the moment a producer emits a UTC offset rather than
    ``Z``. Missing or unparseable timestamps sort lowest and ties break by latest
    input order. The returned dict is the signal augmented with ``source`` and
    ``timestamp`` from the winning entry.
    """
    best = None
    best_key = None
    for index, entry in enumerate(entries or []):
        if not isinstance(entry, dict):
            continue
        signal = detect_signal(entry.get("body"))
        if signal is None:
            continue
        timestamp = entry.get("timestamp")
        key = (_sort_key(timestamp), index)
        if best_key is None or key > best_key:
            best_key = key
            best = dict(signal)
            best["source"] = entry.get("source")
            best["timestamp"] = timestamp
    return best
