#!/usr/bin/env python3
"""Build and read summary and per-finding signals; version never selects a reader.
Canonical footer: Generated by code-gauntlet | Reviewed up to: <sha>
"""

import json
import math
import re
from collections.abc import Iterable
from datetime import datetime, timezone
from typing import Final, Literal, NoReturn, TypedDict, TypeGuard, cast


class FindingMarkerWire(TypedDict):
    sha: str
    key: str


class SignalWire(TypedDict):
    sha: str
    signal: Literal["marker", "footer"]
    legacy: bool
    marker: dict[str, object] | None


class SelectedSignalWire(SignalWire, total=False):
    source: object
    timestamp: object


MARKER_TOKEN: Final = "code-gauntlet-findings"
LEGACY_MARKER_TOKEN: Final = "deep-review-findings"
MARKER_TOKENS = (MARKER_TOKEN, LEGACY_MARKER_TOKEN)
# The required colon keeps finding and summary tokens disjoint.
FINDING_MARKER_TOKEN: Final = "code-gauntlet-finding-key"
PRODUCT = "code-gauntlet"
LEGACY_PRODUCT = "deep-review"
MARKER_VERSION = "3.0"  # informational; never dispatched on
SHA_RE = re.compile(r"\b([0-9a-f]{7,40})\b")  # git object ids are lowercase hex

# Matching only openers avoids rescanning payloads from every hostile candidate.
_MARKER_OPENER_RE = re.compile(
    r"<!--\s*(" + "|".join(re.escape(t) for t in MARKER_TOKENS) + r")\s*:\s*(?=\{)"
)

_FINDING_MARKER_RE = re.compile(
    r"<!--\s*" + re.escape(FINDING_MARKER_TOKEN) + r"\s*:\s*(\{[^{}]*\})\s*-->"
)
_FINDING_KEY_RE = re.compile(r"[0-9a-f]{16}")

_PROSE_LABEL_RE = re.compile(r"Reviewed\s+up\s+to\s*:", re.IGNORECASE)

_ISO8601_RE = re.compile(r"^\d{4}-\d{2}-\d{2}")


def is_sha_shaped(value: object) -> TypeGuard[str]:
    """Return True when *value* is a 7-40 character lowercase hex git object id."""
    return isinstance(value, str) and SHA_RE.fullmatch(value.strip()) is not None


def build_marker(sha: object, findings_count: object) -> str:
    """Return the published version/count/SHA marker in that key order."""
    payload = {
        "version": MARKER_VERSION,
        "findings_count": findings_count,
        "sha": sha,
    }
    return f"<!-- {MARKER_TOKEN}: {json.dumps(payload, separators=(',', ':'))} -->"


def build_finding_marker(sha: object, key: object) -> str:
    """Return a sha/key marker; invalid keys remain unreadable for deduplication."""
    payload = {"sha": sha, "key": key}
    return (
        f"<!-- {FINDING_MARKER_TOKEN}: {json.dumps(payload, separators=(',', ':'))} -->"
    )


def build_prose_footer(sha: object) -> str:
    """Return the human footer without surrounding newlines."""
    return f"Generated by {PRODUCT} | Reviewed up to: {sha}"


def build_footer(
    findings_count: object, sha: object, *, prose_body: object = None
) -> str:
    """Always append the mechanical marker; avoid repeating same-SHA prose."""
    marker = build_marker(sha, findings_count)
    if has_prose_footer(prose_body) and parse_prose_footer(prose_body) == sha:
        return "\n\n" + marker
    return "\n\n---\n" + build_prose_footer(sha) + "\n\n" + marker


def _has_non_finite(value: object, depth: int = 0) -> bool:
    """Overflowing numeric tokens bypass parse_constant and would corrupt stdout."""
    if depth > 64:
        return True
    if isinstance(value, float):
        return math.isnan(value) or value in (float("inf"), float("-inf"))
    if isinstance(value, dict):
        return any(_has_non_finite(v, depth + 1) for v in value.values())
    if isinstance(value, list):
        return any(_has_non_finite(v, depth + 1) for v in value)
    return False


def _reject_constant(name: str) -> NoReturn:
    """Reject nonstandard constants before they can corrupt the JSON receipt."""
    raise ValueError(f"non-standard JSON constant: {name}")


def find_marker(text: object) -> dict[str, object] | None:
    """Read only a complete summary marker at the end of the body."""
    if not isinstance(text, str) or not text:
        return None
    tail = text.rstrip()
    if not tail.endswith("-->"):
        return None
    match = None
    for candidate in _MARKER_OPENER_RE.finditer(tail):
        match = candidate
    if match is None:
        return None
    try:
        payload, end = json.JSONDecoder(parse_constant=_reject_constant).raw_decode(
            tail, match.end()
        )
    except (ValueError, RecursionError):
        return None
    if (
        tail[end:].lstrip() != "-->"
        or not isinstance(payload, dict)
        or _has_non_finite(payload)
    ):
        return None
    found = dict(cast(dict[str, object], payload))
    found["_token"] = match.group(1)
    found["_legacy"] = match.group(1) == LEGACY_MARKER_TOKEN
    return found


def find_finding_markers(text: object) -> list[FindingMarkerWire]:
    """Read valid sha/key pairs in the trailing run, in reverse order.

    A group delivers all its members in one body, so omitting keys would repost
    those members. Validate keys before the caller puts them in a set.
    """
    if not isinstance(text, str) or not text:
        return []
    found: list[FindingMarkerWire] = []
    try:
        tail = text.rstrip()
        candidates: list[str] = []
        for line in reversed(tail.splitlines()):
            if not line.strip():
                continue
            match = _FINDING_MARKER_RE.fullmatch(line.strip())
            if match is None:
                break
            candidates.append(match.group(1))
        for candidate in candidates:
            try:
                payload: dict[str, object] = json.loads(candidate)
            except (ValueError, RecursionError):
                continue
            # No isinstance(dict) guard: the regex above spans a brace-delimited
            # literal, so a successful parse cannot be anything else.
            key = payload.get("key")
            if not isinstance(key, str) or not _FINDING_KEY_RE.fullmatch(key):
                continue
            sha = payload.get("sha")
            if not is_sha_shaped(sha):
                continue
            found.append({"sha": sha.strip(), "key": key})
        return found
    except Exception:  # noqa: BLE001  # pragma: no cover - a reader never raises
        return found


def has_prose_footer(text: object) -> bool:
    """Recognize attribution from either product generation."""
    if not isinstance(text, str):
        return False
    return f"Generated by {PRODUCT}" in text or f"Generated by {LEGACY_PRODUCT}" in text


def parse_prose_footer(text: object) -> str | None:
    """Read the last SHA-shaped token following a Reviewed-up-to label.

    Tolerates backticks, markdown emphasis, and a trailing ``|`` around the SHA.
    Never raises.
    """
    if not isinstance(text, str) or not text:
        return None
    try:
        found = None
        for match in _PROSE_LABEL_RE.finditer(text):
            tail = text[match.end() :]
            newline = tail.find("\n")
            if newline != -1:
                tail = tail[:newline]
            sha_match = SHA_RE.search(tail)
            if sha_match:
                found = sha_match.group(1)
        return found
    except Exception:  # noqa: BLE001  # pragma: no cover - a reader never raises
        return None


def _prose_is_legacy(text: object) -> bool:
    """True when only the pre-rename product name appears in *text*."""
    if not isinstance(text, str):
        return False
    if f"Generated by {PRODUCT}" in text:
        return False
    return f"Generated by {LEGACY_PRODUCT}" in text


def detect_signal(text: object) -> SignalWire | None:
    """Prefer a trailing marker; try attributed prose only without one.

    A bare Reviewed-up-to label identifies no tool and must not skip a review.
    """
    if not isinstance(text, str) or not text:
        return None
    marker = find_marker(text)
    if marker is not None:
        marker_sha = marker.get("sha")
        if not is_sha_shaped(marker_sha):
            return None
        return {
            "sha": marker_sha.strip(),
            "signal": "marker",
            "legacy": bool(marker.get("_legacy")),
            "marker": marker,
        }
    tail = text.rstrip().split("\n")[-1]
    sha = parse_prose_footer(tail) if has_prose_footer(tail) else None
    if sha:
        return {
            "sha": sha,
            "signal": "footer",
            "legacy": _prose_is_legacy(tail),
            "marker": None,
        }
    return None


def _sort_key(timestamp: object) -> str:
    """Normalize absolute instants: raw offset spellings can pick an older review.

    Missing or invalid timestamps sort lowest; naive timestamps are UTC.
    """
    if not isinstance(timestamp, str) or not _ISO8601_RE.match(timestamp):
        return ""
    try:
        # fromisoformat only learned to accept a trailing "Z" in 3.11 and the
        # supported floor here is 3.10, so normalize the zone spelling first.
        parsed = datetime.fromisoformat(timestamp.strip().replace("Z", "+00:00"))
    except ValueError:
        return ""
    if parsed.tzinfo is None:
        parsed = parsed.replace(tzinfo=timezone.utc)
    # Offset by an epoch-safe constant so pre-1970 instants stay non-negative and
    # therefore still sort correctly as fixed-width strings.
    return f"{parsed.timestamp() + 1e12:020.6f}"


def select_latest(entries: Iterable[object] | None) -> SelectedSignalWire | None:
    """Read the newest signal, breaking timestamp ties by latest input order."""
    best: SelectedSignalWire | None = None
    best_key = None
    for index, entry in enumerate(entries or []):
        if not isinstance(entry, dict):
            continue
        signal = detect_signal(entry.get("body"))
        if signal is None:
            continue
        timestamp = entry.get("timestamp")
        key = (_sort_key(timestamp), index)
        if best_key is None or key > best_key:
            best_key = key
            best = cast(SelectedSignalWire, dict(signal))
            best["source"] = entry.get("source")
            best["timestamp"] = timestamp
    return best
